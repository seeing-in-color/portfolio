/*
 * Portfolio Q&A endpoint.
 *
 * Streams plain UTF-8 text chunks — the client appends them directly, so there
 * is no SSE envelope to parse. Errors arrive as a non-2xx before any body is
 * written, which keeps the client's failure path simple.
 */

const MODEL = "claude-opus-5";
const MAX_TOKENS = 1600;
const MAX_QUESTION_CHARS = 800;
const MAX_TURNS = 10;

/* Best-effort throttle. Edge instances are ephemeral and not shared, so this
 * adds friction rather than a real guarantee — enough for a portfolio page. */
const RATE_WINDOW_MS = 60_000;
const RATE_MAX = 12;
const hits = new Map();

function throttled(ip) {
  const now = Date.now();
  const recent = (hits.get(ip) ?? []).filter((t) => now - t < RATE_WINDOW_MS);
  recent.push(now);
  hits.set(ip, recent);
  if (hits.size > 5000) hits.clear();
  return recent.length > RATE_MAX;
}

