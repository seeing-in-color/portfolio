export default async function handler(req) {
  if (req.method !== "POST") {
    return new Response("Method not allowed", { status: 405 });
  }
  if (!process.env.ANTHROPIC_API_KEY) {
    return new Response("Assistant is not configured yet.", { status: 503 });
  }

  const ip =
    req.headers.get("x-forwarded-for")?.split(",")[0]?.trim() ?? "unknown";
  if (throttled(ip)) {
    return new Response("Too many questions just now — try again in a minute.", {
      status: 429,
    });
  }

  let messages;
  try {
    const body = await req.json();
    messages = (Array.isArray(body?.messages) ? body.messages : [])
      .filter(
        (m) =>
          (m?.role === "user" || m?.role === "assistant") &&
          typeof m.content === "string" &&
          m.content.trim()
      )
      .slice(-MAX_TURNS)
      .map((m) => ({
        role: m.role,
        content: m.content.slice(0, MAX_QUESTION_CHARS),
      }));
  } catch {
    return new Response("Malformed request.", { status: 400 });
  }

  // The API requires the conversation to start with a user turn.
  while (messages.length && messages[0].role !== "user") messages.shift();
  if (!messages.length) return new Response("No question.", { status: 400 });

  try {
    const upstream = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": process.env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: MODEL,
        max_tokens: MAX_TOKENS,
        stream: true,
        system: [
          { type: "text", text: SYSTEM, cache_control: { type: "ephemeral" } },
        ],
        messages,
      }),
    });

    if (!upstream.ok || !upstream.body) {
      const detail = await upstream.text();
      console.error("chat request failed:", upstream.status, detail);
      const status = upstream.status === 429 ? 429 : 502;
      return new Response("The assistant is unavailable right now.", { status });
    }

    const encoder = new TextEncoder();
    const body = new ReadableStream({
      async start(controller) {
        const reader = upstream.body.getReader();
        const decoder = new TextDecoder();
        let buffer = "";
        let refused = false;

        const processEvent = (event) => {
          const dataLine = event
            .split("\n")
            .find((line) => line.startsWith("data: "));
          if (!dataLine) return;

          let data;
          try {
            data = JSON.parse(dataLine.slice(6));
          } catch {
            return;
          }

          if (
            data.type === "content_block_delta" &&
            data.delta?.type === "text_delta"
          ) {
            controller.enqueue(encoder.encode(data.delta.text));
          }
          if (data.type === "message_delta" && data.delta?.stop_reason === "refusal") {
            refused = true;
          }
        };

        try {
          while (true) {
            const { value, done } = await reader.read();
            buffer += decoder.decode(value, { stream: !done }).replace(/\r\n/g, "\n");

            let boundary;
            while ((boundary = buffer.indexOf("\n\n")) !== -1) {
              processEvent(buffer.slice(0, boundary));
              buffer = buffer.slice(boundary + 2);
            }

            if (done) break;
          }
          if (buffer.trim()) processEvent(buffer);
          if (refused) {
            controller.enqueue(
              encoder.encode(
                "\n\nI can't answer that one. Andres is at dretaq@gmail.com."
              )
            );
          }
        } catch (err) {
          console.error("stream failed:", err);
          controller.enqueue(
            encoder.encode("\n\n(The answer was cut short — please try again.)")
          );
        } finally {
          reader.releaseLock();
          controller.close();
        }
      },
    });

    return new Response(body, {
      headers: {
        "Content-Type": "text/plain; charset=utf-8",
        "Cache-Control": "no-store",
        "X-Accel-Buffering": "no",
      },
    });
  } catch (err) {
    console.error("chat request failed:", err);
    return new Response("The assistant is unavailable right now.", { status: 502 });
  }
}
